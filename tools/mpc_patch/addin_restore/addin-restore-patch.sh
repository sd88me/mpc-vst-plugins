    cat > "$1" <<'INI_PAYLOAD_EOF'
[info]
device=Addin Restore
manufacturer=OpenMPC
script=addin_restore.lua
scriptVersion=1.0
checksum=dd21e94f08aa4e5850c626278b83391867736b52226901d1133d6028259d5e65
INI_PAYLOAD_EOF
}
