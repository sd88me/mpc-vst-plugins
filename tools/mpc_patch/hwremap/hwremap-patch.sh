SO_DROPIN=/data/hwremap/hwremap.so
FAILED=0
STOPPED=0
ROOT_RW=0
WROTE_CONF=0
SVC=
STYLE=
LAYOUT=
OPT_SET=
OPT_WITH=
OPT_WITHOUT=
OPTS=
die() { echo "ERROR: $*" >&2; exit 1; }
usage() { sed -n '2,17p' "$0" | sed 's/^# \{0,1\}//'; exit "${1:-0}"; }

